"""Summarize video metadata and write a human-readable dataset EDA report.

Reports schema, class balance, missing values, media properties, and potential
quality issues from the ``videos.csv`` generated by the scanner.
"""

import pandas as pd
import numpy as np
from pathlib import Path


# ============================================================
# CONFIGURATION
# ============================================================

CSV_PATH = Path(
    "/home/midstan/Documents/Python/VISTA-DF/dataset/K700/metadata/videos.csv"
)

REPORT_PATH = Path(
    "/home/midstan/Documents/Python/VISTA-DF/dataset/K700/metadata/videos_eda_report.txt"
)


# ============================================================
# LOAD DATA
# ============================================================

if not CSV_PATH.exists():
    print(f"ERROR: CSV file not found:")
    print(CSV_PATH)
    exit(1)

df = pd.read_csv(CSV_PATH)


# ============================================================
# HELPER FUNCTIONS
# ============================================================

def section(title):
    """Print a visual heading directly to the console."""
    print("\n")
    print("=" * 80)
    print(title)
    print("=" * 80)


def subsection(title):
    """Print a smaller visual heading directly to the console."""
    print("\n" + "-" * 80)
    print(title)
    print("-" * 80)


# ============================================================
# REPORT STORAGE
# ============================================================

report_lines = []


def report(text=""):
    """Print one report line and retain it for the output text file."""
    print(text)
    report_lines.append(str(text))


def report_section(title):
    """Add a formatted section heading to both console and saved report."""
    report("")
    report("=" * 80)
    report(title)
    report("=" * 80)


def report_subsection(title):
    """Add a formatted subsection heading to both report destinations."""
    report("")
    report("-" * 80)
    report(title)
    report("-" * 80)


# ============================================================
# START
# ============================================================

report_section("VISTA-DF DATASET EDA REPORT")

report(f"CSV file:")
report(str(CSV_PATH))

report(f"Rows: {len(df)}")
report(f"Columns: {len(df.columns)}")


# ============================================================
# 1. COLUMN INFORMATION
# ============================================================

report_section("1. COLUMN INFORMATION")

for column in df.columns:
    report(
        f"{column:20} | "
        f"dtype = {df[column].dtype}"
    )


# ============================================================
# 2. BASIC DATASET INFORMATION
# ============================================================

report_section("2. BASIC DATASET INFORMATION")

report(f"Total records/videos : {len(df)}")
report(f"Total columns        : {len(df.columns)}")
report(f"Duplicate rows       : {df.duplicated().sum()}")


if "video_id" in df.columns:
    report(f"Unique video IDs     : {df['video_id'].nunique()}")
    report(
        f"Duplicate video IDs  : "
        f"{df['video_id'].duplicated().sum()}"
    )


# ============================================================
# 3. CLASS DISTRIBUTION
# ============================================================

report_section("3. CLASS DISTRIBUTION")

if "class" in df.columns:

    class_counts = df["class"].value_counts()

    report(f"Total classes : {class_counts.nunique()}")
    report(
        f"Unique class names : "
        f"{df['class'].nunique()}"
    )

    report("")
    report("Videos per class statistics:")

    report(
        str(
            class_counts.describe()
            .round(2)
        )
    )

    report("")
    report("Minimum videos in a class:")
    report(
        f"{class_counts.min()}"
    )

    report("Maximum videos in a class:")
    report(
        f"{class_counts.max()}"
    )

    report("")
    report("Classes with fewer than 7 videos:")

    fewer_than_7 = class_counts[class_counts < 7]

    if len(fewer_than_7) == 0:
        report("NONE")
    else:
        for class_name, count in fewer_than_7.items():
            report(
                f"{class_name}: {count}"
            )

    report("")
    report("Classes with exactly 7 videos:")

    exactly_7 = (class_counts == 7).sum()

    report(
        f"{exactly_7} classes"
    )

    report("")
    report("Top 10 classes by number of videos:")

    for class_name, count in class_counts.head(10).items():
        report(
            f"{class_name:40} {count}"
        )


# ============================================================
# 4. MISSING VALUES
# ============================================================

report_section("4. MISSING VALUES")

missing = df.isnull().sum()

if missing.sum() == 0:

    report("No missing values found.")

else:

    for column, count in missing.items():

        if count > 0:

            percentage = (
                count / len(df)
            ) * 100

            report(
                f"{column:20} "
                f"{count:8} missing "
                f"({percentage:.2f}%)"
            )


# ============================================================
# 5. STATUS / CORRUPTED FILES
# ============================================================

report_section("5. VIDEO STATUS")

if "status" in df.columns:

    status_counts = df["status"].value_counts(
        dropna=False
    )

    for status, count in status_counts.items():

        percentage = (
            count / len(df)
        ) * 100

        report(
            f"{str(status):30} "
            f"{count:8} "
            f"({percentage:.2f}%)"
        )

    error_count = (
        df["status"]
        .astype(str)
        .str.startswith("ERROR")
        .sum()
    )

    report("")
    report(f"Total videos with errors: {error_count}")


# ============================================================
# 6. AUDIO ANALYSIS
# ============================================================

report_section("6. AUDIO ANALYSIS")

if "has_audio" in df.columns:

    audio_counts = df["has_audio"].value_counts(
        dropna=False
    )

    with_audio = (
        (df["has_audio"] == 1).sum()
    )

    without_audio = (
        (df["has_audio"] == 0).sum()
    )

    report(
        f"Videos with audio    : "
        f"{with_audio}"
    )

    report(
        f"Videos without audio : "
        f"{without_audio}"
    )

    report(
        f"Audio coverage       : "
        f"{(with_audio / len(df)) * 100:.2f}%"
    )

    report("")

    if without_audio > 0:

        report("Videos without audio:")

        no_audio = df[
            df["has_audio"] == 0
        ]

        for _, row in no_audio.iterrows():

            report(
                f"{row.get('video_id', '')} | "
                f"{row.get('class', '')} | "
                f"{row.get('path', '')}"
            )

    else:

        report(
            "All videos contain an audio stream."
        )


# ============================================================
# 7. DURATION ANALYSIS
# ============================================================

report_section("7. VIDEO DURATION ANALYSIS")

if "duration_sec" in df.columns:

    duration = pd.to_numeric(
        df["duration_sec"],
        errors="coerce"
    )

    report(
        str(
            duration.describe()
            .round(3)
        )
    )

    report("")
    report(
        f"Total duration: "
        f"{duration.sum() / 3600:.2f} hours"
    )

    report(
        f"Mean duration: "
        f"{duration.mean():.2f} seconds"
    )

    report(
        f"Median duration: "
        f"{duration.median():.2f} seconds"
    )

    report(
        f"Shortest video: "
        f"{duration.min():.2f} seconds"
    )

    report(
        f"Longest video: "
        f"{duration.max():.2f} seconds"
    )


# ============================================================
# 8. DURATION BINS
# ============================================================

report_section("8. VIDEO DURATION DISTRIBUTION")

if "duration_sec" in df.columns:

    duration = pd.to_numeric(
        df["duration_sec"],
        errors="coerce"
    )

    bins = [
        0,
        2,
        5,
        10,
        15,
        20,
        30,
        60,
        np.inf
    ]

    labels = [
        "<=2 sec",
        "2-5 sec",
        "5-10 sec",
        "10-15 sec",
        "15-20 sec",
        "20-30 sec",
        "30-60 sec",
        ">60 sec"
    ]

    duration_groups = pd.cut(
        duration,
        bins=bins,
        labels=labels,
        include_lowest=True
    )

    duration_counts = duration_groups.value_counts(
        sort=False
    )

    for label, count in duration_counts.items():

        percentage = (
            count / len(df)
        ) * 100

        report(
            f"{str(label):15} "
            f"{count:8} "
            f"({percentage:.2f}%)"
        )


# ============================================================
# 9. FPS ANALYSIS
# ============================================================

report_section("9. FPS ANALYSIS")

if "fps" in df.columns:

    fps = pd.to_numeric(
        df["fps"],
        errors="coerce"
    )

    report(
        str(
            fps.describe()
            .round(3)
        )
    )

    report("")
    report("Most common FPS values:")

    fps_counts = (
        fps.round(2)
        .value_counts()
        .head(15)
    )

    for value, count in fps_counts.items():

        report(
            f"{value:10} FPS : {count}"
        )


# ============================================================
# 10. RESOLUTION ANALYSIS
# ============================================================

report_section("10. RESOLUTION ANALYSIS")

if "width" in df.columns and "height" in df.columns:

    resolution = (
        df["width"].astype(str)
        + "x"
        + df["height"].astype(str)
    )

    resolution_counts = (
        resolution.value_counts()
    )

    report(
        f"Unique resolutions: "
        f"{resolution.nunique()}"
    )

    report("")
    report("Most common resolutions:")

    for resolution_name, count in resolution_counts.head(15).items():

        percentage = (
            count / len(df)
        ) * 100

        report(
            f"{resolution_name:15} "
            f"{count:8} "
            f"({percentage:.2f}%)"
        )


# ============================================================
# 11. FILE SIZE ANALYSIS
# ============================================================

report_section("11. FILE SIZE ANALYSIS")

if "file_size_mb" in df.columns:

    file_size = pd.to_numeric(
        df["file_size_mb"],
        errors="coerce"
    )

    report(
        str(
            file_size.describe()
            .round(3)
        )
    )

    report("")
    report(
        f"Total dataset size: "
        f"{file_size.sum() / 1024:.2f} GB"
    )


# ============================================================
# 12. POTENTIALLY PROBLEMATIC VIDEOS
# ============================================================

report_section("12. POTENTIALLY PROBLEMATIC VIDEOS")

problem_found = False


# Zero/invalid duration

if "duration_sec" in df.columns:

    invalid_duration = df[
        pd.to_numeric(
            df["duration_sec"],
            errors="coerce"
        ) <= 0
    ]

    if len(invalid_duration) > 0:

        problem_found = True

        report(
            f"Videos with invalid duration: "
            f"{len(invalid_duration)}"
        )

        for _, row in invalid_duration.iterrows():

            report(
                f"  {row.get('video_id', '')} | "
                f"{row.get('path', '')}"
            )


# Invalid FPS

if "fps" in df.columns:

    invalid_fps = df[
        pd.to_numeric(
            df["fps"],
            errors="coerce"
        ) <= 0
    ]

    if len(invalid_fps) > 0:

        problem_found = True

        report(
            f"Videos with invalid FPS: "
            f"{len(invalid_fps)}"
        )


# Missing audio

if "has_audio" in df.columns:

    no_audio = df[
        df["has_audio"] == 0
    ]

    if len(no_audio) > 0:

        problem_found = True

        report(
            f"Videos without audio: "
            f"{len(no_audio)}"
        )


# Errors

if "status" in df.columns:

    errors = df[
        df["status"]
        .astype(str)
        .str.startswith("ERROR")
    ]

    if len(errors) > 0:

        problem_found = True

        report(
            f"Videos with metadata errors: "
            f"{len(errors)}"
        )


if not problem_found:

    report(
        "No obvious problems detected from the CSV metadata."
    )


# ============================================================
# 13. DATASET SUITABILITY SUMMARY
# ============================================================

report_section("13. DATASET SUMMARY FOR VISTA-DF")

report(
    f"Total videos              : {len(df)}"
)

if "class" in df.columns:
    report(
        f"Total classes             : "
        f"{df['class'].nunique()}"
    )

if "has_audio" in df.columns:
    report(
        f"Videos with audio         : "
        f"{(df['has_audio'] == 1).sum()}"
    )

if "duration_sec" in df.columns:
    duration = pd.to_numeric(
        df["duration_sec"],
        errors="coerce"
    )

    report(
        f"Average duration          : "
        f"{duration.mean():.2f} sec"
    )

    report(
        f"Median duration           : "
        f"{duration.median():.2f} sec"
    )

if "fps" in df.columns:

    fps = pd.to_numeric(
        df["fps"],
        errors="coerce"
    )

    report(
        f"Average FPS               : "
        f"{fps.mean():.2f}"
    )


# ============================================================
# 14. RECOMMENDATION
# ============================================================

report_section("14. NEXT DATASET PROCEDURE")

report(
    "1. Verify the number of videos per class."
)

report(
    "2. Verify audio availability."
)

report(
    "3. Check videos with metadata errors."
)

report(
    "4. Create video-level train/validation/holdout splits."
)

report(
    "5. Create temporal-window metadata after splitting."
)


# ============================================================
# SAVE REPORT
# ============================================================

REPORT_PATH.parent.mkdir(
    parents=True,
    exist_ok=True
)

with open(
    REPORT_PATH,
    "w",
    encoding="utf-8"
) as f:

    f.write("\n".join(report_lines))


# ============================================================
# FINAL MESSAGE
# ============================================================

print("\n")
print("=" * 80)
print("EDA COMPLETE")
print("=" * 80)

print(f"Report saved to:")
print(REPORT_PATH)

print("=" * 80)
